-- Подтверждение заказа доходит не всегда: покупатель мог открыть магазин
-- с иконки или из профиля бота, ни разу ему не написав, — тогда бот не вправе
-- писать первым. Флаг помнит, кому подтверждение ещё должно уйти: бот дошлёт
-- его, как только покупатель напишет.
ALTER TABLE orders ADD COLUMN customer_notified INTEGER NOT NULL DEFAULT 0;

-- Старые заказы дошли или уже неактуальны — дошлём только новые.
UPDATE orders SET customer_notified = 1;
